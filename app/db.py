PG_SCHEMA = SCHEMA.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")

_pool = None


def _pg_pool():
    global _pool
    if _pool is None:
        from psycopg.rows import dict_row
        from psycopg_pool import ConnectionPool

        _pool = ConnectionPool(
            DATABASE_URL,
            min_size=1,
            max_size=4,
            timeout=10,
            kwargs={"row_factory": dict_row, "prepare_threshold": None, "autocommit": True},
            open=True,
        )
        _pool.wait(timeout=10)
    return _pool


def connect():
    if IS_POSTGRES:
        return _pg_pool().getconn()
    os.makedirs(DATA_DIR, exist_ok=True)
    con = sqlite3.connect(DB_PATH)
    con.row_factory = sqlite3.Row
    con.execute("PRAGMA foreign_keys = ON")
    return con


def _release(con):
    if IS_POSTGRES:
        _pg_pool().putconn(con)
    else:
        con.close()


def _pg_sql(sql):
    return sql.replace("?", "%s")


def rows(sql, params=()):
    con = connect()
    try:
        if IS_POSTGRES:
            with con.cursor() as cur:
                cur.execute(_pg_sql(sql), params)
                return cur.fetchall()
        return con.execute(sql, params).fetchall()
    finally:
        _release(con)


def row(sql, params=()):
    con = connect()
    try:
        if IS_POSTGRES:
            with con.cursor() as cur:
                cur.execute(_pg_sql(sql), params)
                return cur.fetchone()
        return con.execute(sql, params).fetchone()
    finally:
        _release(con)


def scalar(sql, params=(), default=None):
    r = row(sql, params)
    if r is None:
        return default
    if isinstance(r, dict):
        return next(iter(r.values()))
    return r[0]


def execute(sql, params=()):
    con = connect()
    try:
        if IS_POSTGRES:
            with con.cursor() as cur:
                cur.execute(_pg_sql(sql), params)
                fetched = cur.fetchone() if cur.description else None
            con.commit()
            if not fetched:
                return None
            return next(iter(fetched.values())) if isinstance(fetched, dict) else fetched[0]
        cur = con.execute(sql, params)
        con.commit()
        return cur.lastrowid
    finally:
        _release(con)


def execute_many(sql, seq):
    con = connect()
    try:
        if IS_POSTGRES:
            with con.cursor() as cur:
                cur.executemany(_pg_sql(sql), seq)
            con.commit()
            return
        con.executemany(sql, seq)
        con.commit()
    finally:
        _release(con)


def insert_ignore(sql, params=()):
    if IS_POSTGRES:
        stmt = _pg_sql(sql).replace("INSERT OR IGNORE", "INSERT", 1).strip()
        return execute(stmt + " ON CONFLICT DO NOTHING RETURNING id", params)
    return execute(sql, params)


def init_db():
    if IS_POSTGRES:
        with _pg_pool().connection() as con:
            with con.cursor() as cur:
                for stmt in PG_SCHEMA.split(";"):
                    if stmt.strip():
                        cur.execute(stmt)
            con.commit()
        return
    os.makedirs(DATA_DIR, exist_ok=True)
    con = connect()
    try:
        con.executescript(SCHEMA)
        con.commit()
    finally:
        _release(con)


def get_setting(key, default=""):
    r = row("SELECT value FROM settings WHERE key = ?", (key,))
    return r["value"] if r is not None and r["value"] is not None else default


def get_settings():
    return {r["key"]: r["value"] for r in rows("SELECT key, value FROM settings")}


def set_setting(key, value):
    execute(
        "INSERT INTO settings(key, value) VALUES(?, ?) "
        "ON CONFLICT(key) DO UPDATE SET value = excluded.value",
        (key, value),
    )
